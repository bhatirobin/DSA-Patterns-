import java.util.*;
public class foreach 
{
    public static void main(String args[])
    {
        ArrayList<Integer> arr = new ArrayList<>();

        arr.add(464);
        arr.add(984);
        arr.add(84);
        arr.add(435);
        arr.add(376);

        for(int i:arr)
        {
            System.out.println(i+" ");
        }
    }
    
}
