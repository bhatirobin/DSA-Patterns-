import java.util.*;
public class concatination {
     public static void main(String args[])
       {
        Scanner sc = new Scanner(System.in);
        String a;
        String b;
        a = sc.nextLine();
        b = sc.nextLine();
        String c = a+" "+b;
        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
       }
}
